SELECT * FROM CONSULTANT_RECOMMENDATIONS;

-- 7. INGREDIENT INTELLIGENCE
CREATE TABLE ingredients_master (
    ingredient_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    canonical_inci_name VARCHAR(255) NOT NULL UNIQUE,
    category VARCHAR(100) NOT NULL,
    comedogenic_rating INT CHECK (comedogenic_rating BETWEEN 0 AND 5),
    is_pregnancy_safe BOOLEAN DEFAULT TRUE,
    functions TEXT[] DEFAULT '{}',
    education_summary TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
SELECT * FROM ingredients_master;

CREATE TABLE ingredient_synonyms (
    synonym_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ingredient_id UUID NOT NULL REFERENCES ingredients_master(ingredient_id) ON DELETE CASCADE,
    synonym_name VARCHAR(255) UNIQUE NOT NULL
);
SELECT * FROM ingredient_synonyms;

CREATE TABLE ingredient_interactions (
    interaction_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ingredient_a_id UUID NOT NULL REFERENCES ingredients_master(ingredient_id) ON DELETE CASCADE,
    ingredient_b_id UUID NOT NULL REFERENCES ingredients_master(ingredient_id) ON DELETE CASCADE,
    interaction_type VARCHAR(50) NOT NULL,
    severity_level VARCHAR(50) NOT NULL,
    recommendation_text TEXT NOT NULL,
    CONSTRAINT unique_interaction_pair UNIQUE (ingredient_a_id, ingredient_b_id),
    CONSTRAINT prevent_self_interaction CHECK (ingredient_a_id <> ingredient_b_id) -- Rectified
);
SELECT * FROM ingredient_interactions;

-- PERFORMANCE & AI QUERY OPTIMIZATION INDEXES
CREATE INDEX idx_ingredients_inci ON ingredients_master(canonical_inci_name);
CREATE INDEX idx_synonyms_name ON ingredient_synonyms(synonym_name);

-- Added Indexes for AI Context Lookups
CREATE INDEX idx_routines_user_active ON ROUTINES(USER_ID, IS_ACTIVE);
CREATE INDEX idx_appointments_patient ON APPOINTMENTS(PATIENT_ID);
CREATE INDEX idx_appointments_consultant ON APPOINTMENTS(CONSULTANT_ID);
CREATE INDEX idx_skinassessment_user ON SKINASSESSMENT(USER_ID);
CREATE INDEX idx_progress_logs_user_date ON PROGRESS_LOGS(USER_ID, LOG_DATE);
