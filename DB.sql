-- Create ENUM types
DO $$ BEGIN
    CREATE TYPE USER_ROLE AS ENUM('USER', 'CONSULTANT', 'DERMATOLOGIST', 'ADMIN');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE PROVIDER_TYPE AS ENUM('LOCAL', 'GOOGLE');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- 1. USERS
CREATE TABLE USERS (
    ID SERIAL PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(200) UNIQUE NOT NULL,
    PASSWORD VARCHAR(255) NOT NULL,
    ROLE USER_ROLE NOT NULL,
    PROVIDER PROVIDER_TYPE DEFAULT 'LOCAL',
    STATUS VARCHAR(20) DEFAULT 'PENDING', -- Secure default fallback
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
SELECT * FROM USERS;

-- Trigger for role-based status assignment
CREATE OR REPLACE FUNCTION auto_assign_user_status()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.ROLE IN ('CONSULTANT', 'DERMATOLOGIST') THEN
        NEW.STATUS := 'PENDING';
    ELSE
        NEW.STATUS := 'APPROVED';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_assign_user_status
BEFORE INSERT ON USERS
FOR EACH ROW
EXECUTE FUNCTION auto_assign_user_status();

