-- 5. ROUTINES & ROUTINE_STEPS
CREATE TABLE ROUTINES (
    ID SERIAL PRIMARY KEY,
    USER_ID INT REFERENCES USERS(ID) ON DELETE CASCADE,
    PATIENT_NAME VARCHAR(100),
    SEASONAL_NOTE VARCHAR(255),
    ADAPTATION_SUMMARY TEXT,
    IS_ACTIVE BOOLEAN DEFAULT TRUE,
    HAS_DERMATOLOGIST_OVERRIDE BOOLEAN DEFAULT FALSE,
    DERMATOLOGIST_NOTES TEXT,
    DERMATOLOGIST_STEPS JSONB,
    AUTHORIZED_BY_DERMA_ID INT REFERENCES USERS(ID) ON DELETE SET NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
