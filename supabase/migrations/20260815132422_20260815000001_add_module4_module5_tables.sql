/*
# Module 4 & Module 5 — Skin Intelligence, Personalized Skincare, and Ingredient Intelligence

## Overview
This migration adds the database tables required for:
- Module 4: Personalized routines (morning/evening/weekly/seasonal), adaptive routine updates, user feedback on routines, and product recommendations.
- Module 5: Ingredient library, personalized ingredient suitability, ingredient interaction analysis, and allergy detection.

## New Tables

1. `routines` — Stores AI-generated personalized skincare routines for a user. Each routine is linked to an assessment and contains structured JSON for morning, evening, weekly, and seasonal plans. Tracks whether the routine was generated by Gemini AI or the rule-based fallback.
2. `routine_feedback` — Stores user feedback after following a routine. Includes improvement status, side effects (irritation, redness, dryness, burning, breakouts), ingredient-specific feedback, and free-text notes. Used to influence future routine generation.
3. `adaptive_updates` — Stores the comparison between a previous and latest assessment, including score trend, concern changes, and Gemini-generated routine adjustments.
4. `products` — Product catalog for recommendations. Stores product name, brand, category, key ingredients, purchase link, and suitability metadata.
5. `product_recommendations` — Links products to assessments with personalized reasoning and allergy/suitability check results.
6. `ingredients` — Ingredient library with structured metadata: category, description, benefits, suitable skin types, common concerns, cautions, interactions, and educational content.
7. `ingredient_interactions` — Known interaction rules between ingredient pairs: risk level, description, and scheduling recommendations.
8. `ingredient_analyses` — Stores personalized ingredient suitability analyses for a user, generated by Gemini or the deterministic fallback. Includes suitability score, reasoning, benefits, cautions, and recommended usage.

## Modified Tables

### user_profiles (extended)
Added columns for:
- `allergies` (text) — Known allergies (e.g., fragrance, nuts, latex)
- `skincare_goals` (text) — User's skincare goals (e.g., anti-aging, acne control)
- `current_products` (text) — Current skincare products being used
- `previous_ingredient_issues` (text) — Ingredients that previously caused issues

## Security (RLS)
- All new tables have RLS enabled.
- Owner-scoped CRUD for user data (routines, feedback, adaptive updates, ingredient analyses, product recommendations).
- Staff (consultant, dermatologist, admin) can read user data for dashboard synchronization.
- Ingredients, ingredient_interactions, and products are readable by all authenticated users (shared reference data).
- Only authenticated users can insert/update their own data.

## Important Notes
1. `user_id` columns on owner-scoped tables default to `auth.uid()` so inserts that omit `user_id` still satisfy RLS.
2. All new tables use `gen_random_uuid()` for primary keys.
3. Indexes added for frequently-queried columns (user_id, assessment_id, routine_id).
4. Existing data is never modified or deleted — only new columns and tables are added.
*/

